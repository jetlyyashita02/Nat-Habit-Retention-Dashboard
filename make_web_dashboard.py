def _href(page_label: str) -> str:
    if page_label in PAGE_HREF:
        return PAGE_HREF[page_label]
    for k, v in PAGE_HREF.items():
        if k in str(page_label):
            return v
    return "insights.html"


def _r(x, nd=3):
    """float or None (NaN-safe)."""
    if x is None:
        return None
    try:
        x = float(x)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(x) else round(x, nd)


def _safe(fn, default):
    try:
        return fn()
    except Exception:
        return default


