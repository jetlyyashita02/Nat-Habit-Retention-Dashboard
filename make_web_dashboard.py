def page_ntc(ctx, D) -> dict:
    ntc = ctx.get("ntc")
    if not ntc:
        return {"body": "<div class='card'><div class='note'>Source not loaded.</div></div>", "data": {"cuts": []}, "js": ""}
    k = ntc_kpis(ntc["df"], ntc["as_of"], ntc["maturity_days"])
    d = ntc["df"].copy()
    d["mature"] = pd.to_datetime(d["cohort"]) + pd.Timedelta(days=ntc["maturity_days"]) <= pd.Timestamp(ntc["as_of"])
    mat = d[d["mature"]]

    def wavg(col, ncol):
        w = mat[ncol].fillna(0)
        v = mat[col]
        ok = v.notna() & (w > 0)
        return float((v[ok] * w[ok]).sum() / w[ok].sum()) if ok.any() else None

    order_cols = [("sec", "2nd order"), ("third", "3rd order"), ("fourth", "4th order"), ("fifth", "5th order"), ("sixth", "6th order")]
    curve = []
    colors = ["#0b6e4f", "#2f8f6b", "#5aa787", "#8cc4a5", "#bfe0cd"]
    for i, (pref, lab) in enumerate(order_cols):
        v = wavg(f"{pref}_pct", f"{pref}_order")
        if v is not None:
            curve.append({"label": lab, "value": v, "vlabel": fmt_pct(v),
                          "tip": f"avg {lab} rate across {fmt_int(k['cohorts_mature'])} mature cohorts", "color": colors[i]})
    ylabels = [str(c) for c in d["cohort"]]
    vals = [[_r(float(r[f"{pref}_pct"]), 4) if pd.notna(r[f"{pref}_pct"]) else None for pref, _ in order_cols]
            for _, r in d.iterrows()]
